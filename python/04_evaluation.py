def calibration_intercept_slope(
    y,
    probability
):
    """
    Estimate calibration intercept and slope by fitting:

        logit(y_probability) -> y

    Intercept near 0 and slope near 1 indicate good calibration.

    This is a descriptive test-set calculation and should not be used to
    recalibrate the final model on the test set.
    """

    from scipy.special import logit
    from sklearn.linear_model import LogisticRegression

    epsilon = 1e-6

    probability_clipped = np.clip(
        probability,
        epsilon,
        1 - epsilon
    )

    logit_probability = logit(
        probability_clipped
    ).reshape(-1, 1)

    calibration_model = LogisticRegression(
        penalty=None,
        solver="lbfgs",
        max_iter=2000
    )

    calibration_model.fit(
        logit_probability,
        y
    )

    intercept = (
        calibration_model.intercept_[0]
    )

    slope = (
        calibration_model.coef_[0][0]
    )

    return intercept, slope


